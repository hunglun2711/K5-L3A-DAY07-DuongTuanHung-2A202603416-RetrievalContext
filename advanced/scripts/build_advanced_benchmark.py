def main() -> None:
    chunks = json.loads(CHUNKS_PATH.read_text(encoding="utf-8"))
    chunk_by_id = {c["id"]: c for c in chunks}
    questions = build_questions()

    dev_q = [q for q in questions if q["split"] == "dev"]
    test_q = [q for q in questions if q["split"] == "test"]
    assert len(dev_q) == 18, f"Expected 18 dev, got {len(dev_q)}"
    assert len(test_q) == 30, f"Expected 30 test, got {len(test_q)}"
    assert Counter(q["primary_group"] for q in dev_q) == {
        "table": 3, "image_diagram": 3, "chart": 3, "multi_hop": 3, "text": 3, "unanswerable": 3
    }
    assert Counter(q["primary_group"] for q in test_q) == {
        "table": 6, "image_diagram": 5, "chart": 5, "multi_hop": 4, "text": 4, "unanswerable": 6
    }

    # Verify non-overlap & valid gold chunks/crops
    assert len({q["question"].casefold() for q in questions}) == len(questions)
    for q in questions:
        for cid in q["gold_evidence"]["chunk_ids"]:
            if cid not in chunk_by_id:
                raise KeyError(f"{q['id']}: missing gold chunk_id {cid} in advanced_chunks.json")
        for cp in q["gold_evidence"]["crop_paths"]:
            if not (REPO_ROOT / cp).exists():
                raise FileNotFoundError(f"{q['id']}: missing crop file {cp}")

    BENCH_DIR.mkdir(parents=True, exist_ok=True)
    (BENCH_DIR / "questions.json").write_text(
        json.dumps(questions, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    # Minimal runtime cases without gold answers/evidence
    runtime_cases = [
        {
            "id": q["id"],
            "split": q["split"],
            "primary_group": q["primary_group"],
            "answerable": q["answerable"],
            "question": q["question"],
        }
        for q in questions
    ]
    (BENCH_DIR / "cases.json").write_text(
        json.dumps(runtime_cases, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Built & verified Advanced benchmark: dev={len(dev_q)}, test={len(test_q)} (total={len(questions)})")


if __name__ == "__main__":
    main()
